/**
 * A device-wide running total that one or more [Achievement]s are measured against. Shared rather
 * than per-achievement so "finish 10 / 50 / 100 games" is one stored number, not three.
 *
 * An [isFlags] counter stores a set of flags, one bit each, rather than a total: its progress is how
 * many are set ([progressOf]), and a game adds its flags with a bitwise or.
 *
 * [cloudMerge] is how the cloud save combines devices' values of it.
 */
enum class AchievementCounter(
    override val id: String,
    val isFlags: Boolean = false,
    val cloudMerge: CounterMerge = if (isFlags) CounterMerge.FLAGS else CounterMerge.SUM,
) : StoredId {
    GAMES_PLAYED("GAMES_PLAYED"),
    GAMES_WON("GAMES_WON"),
    WIN_STREAK("WIN_STREAK", cloudMerge = CounterMerge.LATEST),
    SCORED_5X("SCORED_5X"),
    DICE_ROLLED("DICE_ROLLED"),

    /** Each number player 1 has scored a 5x of: bit `n - 1` for the number `n`. */
    FIVE_X_NUMBERS("FIVE_X_NUMBERS", isFlags = true),

    /** Each of [Achievement.FULL_HOUSES_HANDS] player 1 has scored a Full House with: bit `n - 1` for the `n`th. */
    FULL_HOUSES("FULL_HOUSES", isFlags = true),
    ;

    /** How far [stored] - this counter's stored value - counts towards an achievement's target. */
    fun progressOf(stored: Int): Int = if (isFlags) stored.countOneBits() else stored

    /** [stored] with [number] (from 1) marked, for a counter of flags ([isFlags]): bit `number - 1`. */
    fun withFlag(stored: Int, number: Int): Int = stored or (1 shl (number - 1))

    /** Whether [stored] has [number] marked - see [withFlag]. */
    fun hasFlag(stored: Int, number: Int): Boolean = stored and (1 shl (number - 1)) != 0
}

/** How the cloud save combines one [AchievementCounter] from several devices. */
enum class CounterMerge {
    /** Each device's own share, added up: games played on two phones count on both. */
    SUM,

    /** Every flag any device has set. */
    FLAGS,

    /** The value from the device that finished a game most recently: a streak runs on one timeline, not one per device. */
    LATEST,
}

/**
 * The longest an [Achievement.title] may be. The unlock banner shows a title on ONE line, shrunk to no
 * smaller than 11sp and never wrapped (every banner is the same size), so a title has to fit its
 * column at that size: 38 characters is the longest there is ("Where We're Going, We Don't Need
 * Rules"), which fits at 11sp on the maintainer's phone (about 345dp wide) with a character or so
 * to spare. Narrower screens and larger system fonts ellipsise it first. A longer title is a project-rule breach - shorten it; see CLAUDE.md. `AchievementTextTest`
 * enforces this.
 *
 * That is the English figure. A character is not the same width in every language, so each translation
 * may set its own `achievement_title_max_length` (a lower one for full-width scripts, say), which the
 * test then holds that language's titles to; one that leaves it out gets this.
 */
const val MAX_ACHIEVEMENT_TITLE_LENGTH = 38

/**
 * What an achievement is *about*, and the order those themes are shown in. Grouping the list this
 * way is what lets one ladder's rungs sit together - "Sharpshooter" then "High Roller" then "Dice
 * Deity" - instead of being scattered across an alphabetical list.
 *
 * [EASTER_EGGS] is last on purpose, and every achievement in it has [AchievementVisibility.HIDDEN]:
 * showing its title with description as "???" until unlocked, and counting towards total and
 * unlocked achievements.
 */
enum class AchievementCategory(val label: StringResource) {
    MILESTONES(Res.string.category_milestones),
    DICE(Res.string.category_dice),
    SCORING(Res.string.category_scoring),
    WINNING(Res.string.category_winning),
    GAME_MODES(Res.string.category_game_modes),
    MISFORTUNE(Res.string.category_misfortune),
    MISCELLANEOUS(Res.string.category_miscellaneous),
    COLLECTION(Res.string.category_collection),
    EASTER_EGGS(Res.string.category_easter_eggs),
}

/** How a locked achievement shows progress, and how eagerly progress is worth announcing. */
enum class ProgressStyle {
    /** One-shot: there is nothing to count, you either did it or you didn't. */
    NONE,

    /** Counts up and never falls. Announced only at quarter marks, or a banner per roll. */
    CUMULATIVE,

    /** Can collapse back to zero at any time, so every step forward is worth announcing. */
    STREAK,
}

/**
 * How much of a locked achievement is shown before it's earned, and how it maps onto a Google Play
 * Games achievement.
 */
enum class AchievementVisibility {
    /** Title and description both visible from the start. Maps to a Play "revealed" achievement. */
    NORMAL,

    /**
     * Title visible, description hidden (shown as "???") until earned. Maps to a Play "hidden"
     * achievement, which Play itself blanks out the description of until revealed/unlocked.
     */
    HIDDEN,
}

/**
 * Every achievement the app tracks. Only player 1 - the human player at this device - earns them; every other seat,
 * human or CPU, is only ever an opponent (see `AchievementEngine`). A game with a modifier on earns none but the
 * modifiers' own ([earnableWithModifiers]).
 *
 * [id] is the stable external key - it is what's written to storage and what a Google Play Games
 * achievement will be mapped to later, so **never change one once released**. It is the enum
 * constant's name in lower case, and the constant is the English [title] in snake case
 * (`AchievementEngineTest` holds the first); a later change to a title's wording leaves both alone. [counter]/[target] describe incremental achievements, which map onto Play's
 * incremental type; [ProgressStyle.STREAK] ones do not (Play's `setSteps` can't go backwards) and
 * become plain unlock-only achievements there, keeping their progress bar locally.
 *
 * **Declaration order is display order.** Entries are grouped by [category] and, within a
 * category, run from easiest to hardest, so a ladder's rungs stay adjacent and in sequence -
 * "Sharpshooter", "High Roller", "Dice Deity". Nothing reads the ordinal, so a new achievement
 * goes wherever it belongs in that reading order rather than on the end; `AchievementEngineTest`
 * fails the build if a category ends up split across the list. Ids are keyed by [id], not
 * position, so reordering is safe for already-stored unlocks.
 *
 * [AchievementCategory.MISCELLANEOUS] and [AchievementCategory.EASTER_EGGS] both contain
 * [AchievementVisibility.HIDDEN] achievements: title visible from the start, description hidden
 * as "???" until earned. `AchievementEngineTest` enforces that all hidden achievements belong
 * to either Miscellaneous or Easter Eggs.
 *
 * [AchievementCategory.EASTER_EGGS] goes at the very end of this enum (after [COMPLETIONIST])
 * rather than filed under its subject's usual category.
 */
enum class Achievement(
    override val id: String,
    val title: StringResource,
    val description: StringResource,
    val category: AchievementCategory,
    val counter: AchievementCounter? = null,
    val target: Int = 1,
    /**
     * For the "collect every score in this range" achievements: the band of final scores that
     * must each have been recorded on the leaderboard at least once. [target] is the number of
     * scores in the band, which `AchievementEngineTest` keeps in step.
     */
    val scoreBand: IntRange? = null,
    /** True for the one achievement measured against every point ever scored, rather than a counter. */
