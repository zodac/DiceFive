    val progressStyle: ProgressStyle
        get() = when {
            // A band only ever gains scores, career points only ever go up, and a mode once played stays played,
            // so all three climb like any other running total.
            scoreBand != null || isCareerPoints || isEveryMode -> ProgressStyle.CUMULATIVE
            // A target of 1 is a plain unlock that happens to be driven by a counter: a "0 of 1"
            // progress bar says nothing the locked state doesn't already.
            counter == null || target <= 1 -> ProgressStyle.NONE
            counter == AchievementCounter.WIN_STREAK -> ProgressStyle.STREAK
            else -> ProgressStyle.CUMULATIVE
        }

    val hasProgressBar: Boolean
        get() = progressStyle != ProgressStyle.NONE

    /**
     * What a collection achievement collects, one entry each, for the list of what's still missing: a score band's
     * scores, the numbers an [AchievementCounter.isFlags] counter's bits stand for (bit `n - 1` for `n`), or for
     * [isEveryMode] each [GameMode]'s position in [GameMode.entries] (for display only, never stored). Null for every
     * other achievement.
     */
    val checklist: List<Int>?
        get() = when {
            scoreBand != null -> scoreBand.toList()
            isEveryMode -> GameMode.entries.indices.toList()
            counter?.isFlags == true -> (1..target).toList()
            else -> null
        }

    /**
     * Whether this can be earned in a game of [gameMode]: any, unless it belongs to [mode] (and [alsoEarnableIn]), or
     * [gameMode] is one of [notEarnableIn] or [impossibleIn].
     */
    fun isEarnableIn(gameMode: GameMode): Boolean =
        (mode == null || mode == gameMode || gameMode in alsoEarnableIn) && gameMode !in notEarnableIn && gameMode !in impossibleIn

    /** Whether this can be earned in [game]: its mode ([isEarnableIn]), and no modifier on unless [earnableWithModifiers]. */
    fun isEarnableIn(game: GameState): Boolean = isEarnableIn(game.gameMode) && (earnableWithModifiers || !game.hasModifiers)

    /**
     * The modes this can be earned in, in [GameMode] order, for one deliberately limited to some ([mode] or
     * [notEarnableIn]); empty for one that isn't, even if some modes' rules rule it out ([impossibleIn]).
     */
    val limitedModes: List<GameMode>
        get() = if (mode == null && notEarnableIn.isEmpty()) emptyList() else GameMode.entries.filter { isEarnableIn(it) }

    companion object {

        /** The achievements [COMPLETIONIST] waits on. */
        val COMPLETION_REQUIREMENTS: List<Achievement> = entries.filter { it.countsTowardCompletion }

        /** The hands [FULL_HOUSES] collects, sorted: the worst Full House there is, then the best. */
        val FULL_HOUSES_HANDS: List<List<Int>> = listOf(listOf(1, 1, 1, 2, 2), listOf(5, 5, 6, 6, 6))

        fun fromId(id: String): Achievement? = storedIdOf<Achievement>(id)
    }
}

/** The ones of these a game of [mode] can earn - see [Achievement.mode]. */
fun Set<Achievement>.earnableIn(mode: GameMode): Set<Achievement> = filterTo(mutableSetOf()) { it.isEarnableIn(mode) }

/** The ones of these [game] can earn: its mode's, and with a modifier on only the modifiers' own - see [Achievement.earnableWithModifiers]. */
fun Set<Achievement>.earnableIn(game: GameState): Set<Achievement> = filterTo(mutableSetOf()) { it.isEarnableIn(game) }
